"""Validate production-file coverage presence and write a portable metrics snapshot."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JS_FILES = sorted(path.name for path in ROOT.glob("*.gs")) + ["gateway/server.js", "gateway/worker.mjs"]
SCANNER = "scripts/verify_repository.py"


def main() -> None:
    summary = json.loads((ROOT / "coverage/coverage-summary.json").read_text())
    js = {Path(name).resolve().relative_to(ROOT).as_posix(): item for name, item in summary.items() if name != "total"}
    if set(js) != set(JS_FILES):
        raise SystemExit("Coverage file set differs from the nine Apps Script files and two gateways")
    if any(item["functions"]["covered"] == 0 for item in js.values()):
        raise SystemExit("A production JS/Apps Script file has no executed functions")
    py = json.loads((ROOT / "coverage/python.json").read_text())
    if set(py["files"]) != {SCANNER}:
        raise SystemExit("Python report must contain exactly the production repository scanner")
    python_summary = py["files"][SCANNER]["summary"]
    if not python_summary["covered_lines"]:
        raise SystemExit("Scanner coverage is empty")
    rows = ["# Production coverage snapshot", "", "Generated by `python scripts/report_coverage.py`; see [method, behavior matrix and limits](coverage.md).", "", "| Source | Lines | Branches | Functions |", "| --- | ---: | ---: | ---: |"]
    for name in [*JS_FILES, "JS total"]:
        item = summary["total"] if name == "JS total" else js[name]
        values = [f'{item[key]["pct"]:.2f}% ({item[key]["covered"]}/{item[key]["total"]})' for key in ["lines", "branches", "functions"]]
        rows.append("| " + name + " | " + " | ".join(values) + " |")
    lines = python_summary["covered_lines"], python_summary["num_statements"]
    branches = python_summary["covered_branches"], python_summary["num_branches"]
    rows.append(f"| {SCANNER} | {100 * lines[0] / lines[1]:.2f}% ({lines[0]}/{lines[1]}) | {100 * branches[0] / branches[1]:.2f}% ({branches[0]}/{branches[1]}) | Not reported by coverage.py |")
    rows += ["", "These are separate tool denominators, not a combined cross-language percentage. No production-file or difficult-path exclusions are configured. Coverage does not prove correctness.", "", "## Source fingerprints", "", "SHA-256 binds these measurements to production file content without a self-referential commit hash.", "", "| Source | SHA-256 |", "| --- | --- |"]
    for name in [*JS_FILES, SCANNER]:
        rows.append(f"| {name} | `{hashlib.sha256((ROOT / name).read_bytes()).hexdigest()}` |")
    rows += ["", "## Uncovered line ranges", "", "V8/c8 statements are mapped to source lines; an executed line can still contain untested branches. Blank/comment lines may be included in V8 line ranges.", ""]
    details = json.loads((ROOT / "coverage/coverage-final.json").read_text())
    for name in JS_FILES:
        item = details[str(ROOT / name)]
        executed, missed = set(), set()
        for key, count in item["s"].items():
            loc = item["statementMap"][key]
            (executed if count else missed).update(range(loc["start"]["line"], loc["end"]["line"] + 1))
        remaining = sorted(missed - executed)
        rows.append(f"- `{name}`: " + (", ".join(map(str, remaining)) or "none") + ".")
    rows.append(f"- `{SCANNER}`: " + ", ".join(map(str, py["files"][SCANNER]["missing_lines"])) + ".")
    (ROOT / "docs/coverage-metrics.md").write_text("\n".join(rows) + "\n")
    print("Verified coverage for all 11 JS/Apps Script production files and the Python scanner; wrote docs/coverage-metrics.md")


if __name__ == "__main__":
    main()
